#ifndef BME280_BME280_REGS_H_
#define BME280_BME280_REGS_H_

#define BME280_I2C_DEVICE_ADDR_GND 0b1110110
#define BME280_I2C_DEVICE_ADDR_VDDIO 0b1110111

#define BME280_ID_ADDR 0xD0
#define BME280_RESET_ADDR 0xE0
#define BME280_STATUS_ADDR 0xF3

#define BME280_CONFIG_ADDR 0xF5
#define BME280_CTRL_HUM_ADDR 0xF2
#define BME280_CTRL_MEAS_ADDR 0xF4

#define BME280_CONFIG_STANDBY 5
#define BME280_CONFIG_FILTER 2
#define BME280_CONFIG_SPI_STATUS 0

#define BME280_STATUS_MEASURING 3
#define BME280_STATUS_IM_UPDATE 0
#define BME280_MODE 0
#define BME280_HUMI_OVS 0
#define BME280_TEMP_OVS 5
#define BME280_PRES_OVS 2

#define BME280_CALIB_TEMP_ADDR_START (0x88)
#define BME280_CALIB_TEMP_ADDR_END (0x8Du)
#define BME280_CALIB_PRES_ADDR_START (0x8Eu)
#define BME280_CALIB_PRES_ADDR_END (0x9Fu)
#define BME280_CALIB_HUMI_ADDR_START (0xA1u)
#define BME280_CALIB_HUMI_ADDR_CONTINUE (0xE1u)
#define BME280_CALIB_HUMI_ADDR_END (0xE7u)

#define BME280_HUMI_LSB_ADDR (0xFEu)
#define BME280_HUMI_MSB_ADDR (0xFDu)
#define BME280_TEMP_XLSB_ADDR (0xFCu)
#define BME280_TEMP_MSB_ADDR (0xFAu)
#define BME280_PRES_XLSB_ADDR (0xF9u)
#define BME280_PRES_MSB_ADDR (0xF7u)

#endif /* BME280_BME280_REGS_H_ */
